import fs from 'node:fs';
const {collectWeeklyEvidence,buildWeeklyArticle}=await import('./dist/src/operations/weekly-review.js');
const {renderWeeklyEditorialArticle}=await import('./dist/src/publishers/editorial-article.js');
const ev=await collectWeeklyEvidence('2026-11-01');
const a=buildWeeklyArticle(ev,{requireCalendar:false});
fs.mkdirSync('out',{recursive:true});
fs.writeFileSync('out/weekly-evidence.json',JSON.stringify(ev,null,2));
fs.writeFileSync('out/weekly-article.json',JSON.stringify(a,null,2));
fs.writeFileSync('out/weekly.html',renderWeeklyEditorialArticle(a).html);
const r=await fetch('https://nfs.faireconomy.media/ff_calendar_thisweek.json');fs.writeFileSync('out/ff-headers.txt',JSON.stringify([...r.headers])+'\n'+(await r.text()).slice(0,300));
